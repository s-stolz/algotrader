from __future__ import annotations

from typing import Any, Protocol

Job = dict[str, Any]


class HistoryStore(Protocol):
    async def get_market_by_id(self, market_id: int) -> Job: ...
    async def create_history_download_job(self, data: Job) -> Job: ...
    async def list_history_download_jobs(
        self, market_id: int | None = None, active_only: bool = False, limit: int = 50
    ) -> list[Job]: ...
    async def get_history_download_job(self, job_id: str) -> Job: ...
    async def claim_history_download_job(
        self, job_id: str, owner_token: str, lease_seconds: int = 120
    ) -> Job | None: ...
    async def heartbeat_history_download_job(
        self, job_id: str, owner_token: str, revision: int, lease_seconds: int = 120
    ) -> Job | None: ...
    async def commit_history_download_page(self, job_id: str, data: Job) -> Job | None: ...
    async def transition_history_download_job(self, job_id: str, data: Job) -> Job | None: ...
    async def cancel_history_download_job(self, job_id: str) -> Job: ...
    async def retry_history_download_job(self, job_id: str) -> Job: ...
